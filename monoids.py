"""What algebra do the token matrices of each component generate?

Belief updating multiplies the state by one matrix per token, so the object that matters is the monoid
generated by a component's token matrices, up to positive scale. This prints what that monoid is for the
components used in this repo.

  python monoids.py
"""
import itertools
import numpy as np
from process import mess3, tom_quantum, fanizza, rrxor

print("=== Tom Quantum: T[tok] acts on the state (1, a, b); G = diag(1, -1, -1)")
G = np.diag([1.0, -1.0, -1.0])
for alpha, beta in ((1, 0.364), (1, 0.839), (1, 2.747), (1, 51 ** 0.5)):
    T = tom_quantum(alpha, beta).T
    m2 = T[0][0, 0] ** 2 - T[0][0, 2] ** 2
    m = m2 ** 0.5
    lorentz = max(np.abs(T[i].T @ G @ T[i] - m2 * G).max() for i in range(4))
    inv = max(np.abs(T[0] @ T[1] - m2 * np.eye(3)).max(), np.abs(T[2] @ T[3] - m2 * np.eye(3)).max())
    B0, B2 = T[0] / m, T[2] / m
    flips = "also flips the sign of the other coordinate" if np.linalg.det(B0) < 0 else "proper"
    C = B0 @ B2 @ np.linalg.inv(B0) @ np.linalg.inv(B2)
    tr = np.trace(C)
    kind = f"a rotation by {np.degrees(np.arccos((tr - 1) / 2)):.2f} degrees" if tr < 3 else f"a boost of rapidity {np.arccosh((tr - 1) / 2):.2f}"
    print(f"beta/alpha {beta:.3f}: each T is {m:.4f} times a Lorentz boost of rapidity {np.arccosh(B0[0, 0]):.3f} ({flips}); "
          f"|T^t G T - m^2 G| = {lorentz:.0e}; tokens 0, 1 and tokens 2, 3 are inverse pairs up to scale ({inv:.0e}); "
          f"|T0 T2 - T2 T0| / m^2 = {np.abs(T[0] @ T[2] - T[2] @ T[0]).max() / m2:.2f}; the commutator of the two boosts is {kind}")

print("\n=== fern (FRDN)")
for alpha, lamb in ((2000, 0.49), (1.0, 0.49), (3.0, 0.45)):
    T = fanizza(alpha, lamb).T
    sv = np.linalg.svd(T[0], compute_uv=False)
    ev = np.linalg.eigvals(T[1])
    ev = ev[np.argsort(-np.abs(ev))]
    ang = np.degrees(np.angle(ev[np.abs(ev.imag) > 1e-9][0]))
    print(f"({alpha}, {lamb}): token 0 has rank {int((sv > 1e-10 * sv[0]).sum())} (it resets the state); token 1 has eigenvalues of modulus "
          + ", ".join(f"{abs(e):.3f}" for e in ev) + f" and turns one plane by {ang % 360:.2f} degrees per step")

print("\n=== Mess3 and the clock: every entry of every T is positive")


def birkhoff(M):
    d = max(np.log(M[i, k] * M[j, l] / (M[i, l] * M[j, k]))
            for i, j in itertools.combinations(range(len(M)), 2) for k, l in itertools.permutations(range(len(M)), 2))
    return np.tanh(d / 4)


for name, comp in (("mess3(0.05, 0.85)", mess3(0.05, 0.85)), ("mess3(0.15, 0.6)", mess3(0.15, 0.6)), ("mess3(0.45, 0.85)", mess3(0.45, 0.85)),
                   ("clock: mess3(0.05, 0.75, shift 1)", mess3(0.05, 0.75, shift=1))):
    T = comp.T
    ev = np.linalg.eigvals(T.sum(0))
    ev = ev[np.argsort(-np.abs(ev))]
    rates = []
    for seed in range(20):                                     # two far-apart beliefs fed the same sampled tokens
        rng = np.random.default_rng(seed)
        b1, b2, ds = np.array([0.98, 0.01, 0.01]), np.array([0.01, 0.01, 0.98]), []
        for t in range(12):
            p = b1 @ T.sum(-1).T
            x = rng.choice(len(T), p=p / p.sum())
            b1, b2 = b1 @ T[x], b2 @ T[x]
            b1, b2 = b1 / b1.sum(), b2 / b2.sum()
            ds.append(np.abs(b1 - b2).sum())
        rates.append((ds[-1] / ds[1]) ** (1 / 10))
    print(f"{name:34s} worst-case contraction per token (Birkhoff coefficient) {max(birkhoff(T[x]) for x in range(3)):.3f}; "
          f"eigenvalues of the token-blind map besides 1: {ev[1]:.3f}, {ev[2]:.3f}; "
          f"two beliefs fed the same tokens close by a factor {np.exp(np.mean(np.log(rates))):.2f} per token")

print("\n=== RRXOR: each (state, token) has at most one successor, so a token is a partial map on the 5 states")
T = rrxor().T
gens = [tuple(int(np.argmax(T[x][s])) if T[x][s].max() > 0 else -1 for s in range(5)) for x in range(2)]
compose = lambda f, g: tuple(g[f[s]] if f[s] >= 0 else -1 for s in range(5))      # first f, then g
monoid, frontier = {tuple(range(5))}, [tuple(range(5))]
while frontier:
    new = []
    for f in frontier:
        for g in gens:
            h = compose(f, g)
            if h not in monoid:
                monoid.add(h)
                new.append(h)
    frontier = new
idem = [f for f in monoid if compose(f, f) == f]


def subgroup(e):
    cand = [f for f in monoid if compose(e, f) == f and compose(f, e) == f]
    return [f for f in cand if any(compose(f, g) == e and compose(g, f) == e for g in cand)]


print(f"tokens as partial maps (state -> state, -1 = impossible): {gens}")
print(f"the monoid they generate has {len(monoid)} elements and {len(idem)} idempotents; its maximal subgroups have sizes {sorted({len(subgroup(e)) for e in idem})}")
